/**
 * @file `pnpm gate:check` / `pnpm gate:render` — WMS release-gate state machine guard.
 * Owning module: repository tooling / release management.
 *
 * docs/WMS_RELEASE_STATUS.json is the single source of truth. This script:
 *   1. validates its semantics (fail-closed): a criterion may be PASS only with evidence, a
 *      verification date and a reviewer; the state may be WMS_PRODUCTION_READY (or later) only
 *      when EVERY criterion is PASS and a named release-owner approval and an independent
 *      security review are recorded; NEXT_MODULE_AUTHORIZED additionally needs the user's
 *      explicit module selection;
 *   2. with `--render`, regenerates docs/WMS_RELEASE_GATE.md from it, so the human-readable
 *      gate can never disagree with the machine-readable status;
 *   3. without `--render`, fails when the committed Markdown is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './dev-env.mjs';

const jsonPath = process.env.WMS_GATE_JSON ?? join(ROOT, 'docs/WMS_RELEASE_STATUS.json'); // override: tests only
const mdPath = join(ROOT, 'docs/WMS_RELEASE_GATE.md');
const s = JSON.parse(readFileSync(jsonPath, 'utf8'));
const errors = [];
const STATUSES = ['PASS', 'FAIL', 'BLOCKED', 'NOT_RUN'];
const READY = ['WMS_PRODUCTION_READY', 'AWAITING_NEXT_MODULE_SELECTION', 'NEXT_MODULE_AUTHORIZED'];

if (!s.allowedStates.includes(s.state)) errors.push(`unknown state ${s.state}`);
const ids = new Set();
for (const c of s.criteria) {
  if (ids.has(c.id)) errors.push(`duplicate criterion ${c.id}`);
  ids.add(c.id);
  if (!STATUSES.includes(c.status)) errors.push(`${c.id}: invalid status ${c.status}`);
  if (c.status === 'PASS' && (!c.evidence?.length || !c.verifiedAt || !c.reviewer)) {
    errors.push(`${c.id}: PASS requires evidence, verifiedAt and reviewer`);
  }
}
const notPassed = s.criteria.filter((c) => c.status !== 'PASS').map((c) => c.id);
if (READY.includes(s.state)) {
  if (notPassed.length) errors.push(`state ${s.state} but criteria not PASS: ${notPassed.join(', ')}`);
  if (!s.releaseOwnerApproval?.name || !s.releaseOwnerApproval?.date) errors.push(`state ${s.state} needs a named release-owner approval`);
  if (!s.independentSecurityReview?.organisation || !s.independentSecurityReview?.reportRef) {
    errors.push(`state ${s.state} needs an independent security review reference`);
  }
}
if (s.state === 'NEXT_MODULE_AUTHORIZED' && !s.nextModuleSelection?.module)
  errors.push('NEXT_MODULE_AUTHORIZED needs the user-selected module');
if (s.state === 'WMS_RELEASE_CANDIDATE') {
  const codeLevel = s.criteria.filter((c) => c.status === 'FAIL').map((c) => c.id);
  if (codeLevel.length) errors.push(`WMS_RELEASE_CANDIDATE requires no FAIL criteria (found ${codeLevel.join(', ')})`);
}

const esc = (v) => String(v ?? '—').replaceAll('|', '\\|');
const count = (st) => s.criteria.filter((c) => c.status === st).length;
const groups = [
  ['F', 'Functional WMS — must all pass'],
  ['E', 'Engineering integrity — must all pass'],
  ['S', 'Security and privacy — must all pass'],
  ['O', 'Operations and handover — must all pass'],
];
let md = `# WMS release gate — ${s.product} v${s.version}

<!-- GENERATED by \`pnpm gate:render\` from docs/WMS_RELEASE_STATUS.json — do not edit by hand. -->

Owning module: release management. Source of criteria: ${s.gateSource}. Evidence details:
\`docs/WMS_RELEASE_EVIDENCE.md\`. Updated: ${s.updatedAt}.

## Current state: \`${s.state}\`

${s.stateReason}

| PASS | FAIL | BLOCKED | NOT_RUN |
| ---- | ---- | ------- | ------- |
| ${count('PASS')} | ${count('FAIL')} | ${count('BLOCKED')} | ${count('NOT_RUN')} |

Release-owner approval: **${s.releaseOwnerApproval ? esc(s.releaseOwnerApproval.name) : 'none recorded'}**. Independent
security review: **${s.independentSecurityReview ? esc(s.independentSecurityReview.organisation) : 'none recorded'}**.
PASS here means "automated evidence reproducible from this repository, self-verified by the
developer"; it is **not** an independent or human sign-off. A release candidate is not a
production-ready product. No other ERP module may start before \`WMS_PRODUCTION_READY\` and the
user's explicit choice of the next module.

State machine: \`WMS_IN_PROGRESS\` → \`WMS_RELEASE_CANDIDATE\` (no FAIL left; only external
items BLOCKED) → \`WMS_PRODUCTION_READY\` (all PASS + named approvals) →
\`AWAITING_NEXT_MODULE_SELECTION\` → \`NEXT_MODULE_AUTHORIZED\`. \`pnpm gate:check\` enforces it.
`;
for (const [prefix, title] of groups) {
  md += `\n## ${title}\n\n| ID | Required result | Verification method | Evidence | Verified at | Reviewer | Status | Open action |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n`;
  for (const c of s.criteria.filter((x) => x.id.startsWith(`${prefix}-`))) {
    md += `| ${c.id} | ${esc(c.requiredResult)} | ${esc(c.verificationMethod)} | ${esc(c.evidence.map((e) => `\`${e}\``).join('<br>') || '—')} | ${esc(c.verifiedAt)} | ${esc(c.reviewer)} | **${c.status}** | ${esc(c.openAction)} |\n`;
  }
}

if (process.argv.includes('--render')) {
  writeFileSync(mdPath, md);
  console.log(`Rendered ${mdPath}`);
}
let current = '';
try {
  current = readFileSync(mdPath, 'utf8');
} catch {
  /* missing */
}
if (!process.argv.includes('--render') && current !== md && !process.argv.includes('--no-render-check')) {
  errors.push('docs/WMS_RELEASE_GATE.md is stale: run pnpm gate:render (then pnpm format)');
}
if (errors.length) {
  console.error(`WMS release gate check FAILED:\n - ${errors.join('\n - ')}`);
  process.exit(1);
}
console.log(
  `WMS release gate OK: state=${s.state}; PASS ${count('PASS')}, FAIL ${count('FAIL')}, BLOCKED ${count('BLOCKED')}, NOT_RUN ${count('NOT_RUN')}`,
);
